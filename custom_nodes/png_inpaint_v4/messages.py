def message(error, language):
    text = str(error)
    if language == 'ru':
        return text
    grok = re.match(r'Grok API: HTTP (\d+)\.', text)
    if grok:
        return f'Grok API returned HTTP {grok[1]}. Check model access and API balance.'
    return _EN.get(text, text)

def request_message(error, request):
    return message(error, request.cookies.get('inpaint_portable_ui', 'en'))
